"""Create final-size trajectory figures for the MoE--PINN manuscript.

The script only visualizes the logged seed-42 trajectory generated by
``jcp_trajectory_logged.py``. It does not retrain a model or alter data.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "Burger2D/results/jcp_reference_rebuild_20260808/trajectory_logged.json"
OUT = ROOT / "docs/JCP_submission_20260808/figure_review"

STAGED = "#2F6B8A"
COADAPT = "#D07A5F"
GRID = "#D9DEE3"
EXPERT_COLORS = ["#0072B2", "#E69F00", "#009E73", "#CC79A7"]
EXPERT_LABELS = ["Smooth", "Iso-shock", "Directional-shock", "Wave"]

plt.rcParams.update({
    "font.family": "sans-serif",
    "font.sans-serif": ["Arial", "DejaVu Sans", "Liberation Sans"],
    "font.size": 7.5,
    "axes.titlesize": 7.5,
    "axes.labelsize": 7.3,
    "xtick.labelsize": 7.2,
    "ytick.labelsize": 7.2,
    "legend.fontsize": 7.2,
    "axes.spines.right": False,
    "axes.spines.top": False,
    "axes.linewidth": 0.8,
    "legend.frameon": False,
    "svg.fonttype": "none",
    "pdf.fonttype": 42,
})


def panel_label(ax: plt.Axes, label: str) -> None:
    ax.text(-0.10, 1.03, label, transform=ax.transAxes, fontsize=8.5,
            fontweight="bold", ha="right", va="bottom")


def save(fig: plt.Figure, stem: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    base = OUT / stem
    fig.savefig(base.with_suffix(".png"), dpi=300, bbox_inches="tight")
    fig.savefig(base.with_suffix(".pdf"), bbox_inches="tight")
    fig.savefig(base.with_suffix(".svg"), bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    co = data["coadapt"]["rows"]
    st = data["staged"]["rows"]
    co_step = np.asarray([r["step"] for r in co])
    st_step = np.asarray([r["step"] for r in st])

    fig, axes = plt.subplots(1, 2, figsize=(7.1, 2.65))
    soft = np.asarray([r["soft_mean"] for r in co])
    grad = np.asarray([r["grad_norms"] for r in co])
    for k, (color, label) in enumerate(zip(EXPERT_COLORS, EXPERT_LABELS)):
        axes[0].plot(co_step, soft[:, k], marker="o", ms=2.5, lw=1.25,
                     color=color, label=label)
        axes[1].plot(co_step, grad[:, k], marker="o", ms=2.5, lw=1.25,
                     color=color, label=label)
    axes[0].set_xlabel("Joint update step")
    axes[0].set_ylabel("Mean soft gate weight")
    axes[0].set_title("Routing mass concentrates during co-adaptation")
    axes[1].set_xlabel("Joint update step")
    axes[1].set_ylabel("Coupled expert-gradient norm")
    axes[1].set_yscale("log")
    axes[1].set_title("Expert-parameter gradients become unequal")
    for ax in axes:
        ax.grid(alpha=0.55, color=GRID, linewidth=0.5)
    axes[0].legend(ncol=2, loc="upper right", handlelength=1.4, columnspacing=0.8)
    panel_label(axes[0], "a")
    panel_label(axes[1], "b")
    fig.tight_layout(w_pad=1.3)
    save(fig, "F13_gradient_coupling_trajectory")

    fig, axes = plt.subplots(1, 2, figsize=(7.1, 2.65))
    axes[0].plot(st_step, [r["gap_q50"] for r in st], "o-", ms=2.8,
                 lw=1.35, color=STAGED, label="Staged")
    axes[0].plot(co_step, [r["gap_q50"] for r in co], "s-", ms=2.8,
                 lw=1.35, color=COADAPT, label="Co-adaptation")
    axes[0].set_yscale("log")
    axes[0].set_xlabel("Training step")
    axes[0].set_ylabel("Median capability gap")
    axes[0].set_title("Capability terrain changes under co-adaptation")
    axes[0].legend()

    axes[1].plot(st_step, [r["flip_rate"] for r in st], "o-", ms=2.8,
                 lw=1.35, color=STAGED, label="Staged")
    axes[1].plot(co_step, [r["flip_rate"] for r in co], "s-", ms=2.8,
                 lw=1.35, color=COADAPT, label="Co-adaptation")
    axes[1].set_xlabel("Training step")
    axes[1].set_ylabel("Oracle-label flip rate")
    axes[1].set_ylim(-0.02, 0.72)
    axes[1].set_title("Pointwise best-expert labels keep changing")
    for ax in axes:
        ax.grid(alpha=0.55, color=GRID, linewidth=0.5)
    panel_label(axes[0], "a")
    panel_label(axes[1], "b")
    fig.tight_layout(w_pad=1.3)
    save(fig, "F12_capability_terrain_trajectory")


if __name__ == "__main__":
    main()
